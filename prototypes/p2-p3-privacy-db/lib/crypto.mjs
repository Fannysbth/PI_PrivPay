// THROWAWAY prototype of the P-3 primitives. node:crypto only (CLAUDE.md: no own crypto, no extra libraries).
import { createCipheriv, createDecipheriv, createHmac, randomBytes } from 'node:crypto';

// Unambiguous encoding for the "||" concatenations in PRD 6/6.2: 4-byte length prefix per part.
// (A bare concatenation lets ("CUST-1","2") and ("CUST-12","") collide.)
export const encodeParts = (...parts) =>
  Buffer.concat(parts.flatMap((p) => {
    const b = Buffer.from(String(p), 'utf8');
    const len = Buffer.alloc(4);
    len.writeUInt32BE(b.length);
    return [len, b];
  }));

export function loadKeys({ kToken, kIndex, kField }) {
  for (const [name, k] of Object.entries({ kToken, kIndex, kField })) {
    if (!Buffer.isBuffer(k) || k.length !== 32) throw new Error(`${name} must be 32 bytes`);
  }
  if (kToken.equals(kIndex) || kToken.equals(kField) || kIndex.equals(kField)) {
    throw new Error('the three keys must differ (FR-30)');
  }
  return { kToken, kIndex, kField };
}

// subject_lookup = HMAC(K_index, subject_type || subject_id)
export const subjectLookup = (kIndex, subjectType, subjectId) =>
  createHmac('sha256', kIndex).update(encodeParts(subjectType, subjectId)).digest();

// pseudonym = "PSEU-" || upper(trunc8hex(HMAC(K_token, type || id || service || purpose || nonce)))
export const tokenValue = (kToken, subjectType, subjectId, serviceId, purpose, nonce) =>
  'PSEU-' + createHmac('sha256', kToken)
    .update(encodeParts(subjectType, subjectId, serviceId, purpose, nonce))
    .digest('hex').slice(0, 8).toUpperCase();

// AAD binds a ciphertext to its context so it cannot be moved: mapping = subject_type + row id,
// vault = column name + row id. The row id is a UUID generated by the application before the INSERT.
export const aadMapping = (subjectType, rowId) => encodeParts('mapping', subjectType, rowId);
export const aadVault = (column, rowId) => encodeParts('vault', column, rowId);

// Format: key_version(uint16 BE) || IV(12) || ciphertext || tag(16); AAD supplied by the caller.
export function encryptField(kField, keyVersion, plaintext, aad) {
  const iv = randomBytes(12);
  const cipher = createCipheriv('aes-256-gcm', kField, iv, { authTagLength: 16 });
  cipher.setAAD(Buffer.from(aad));
  const ct = Buffer.concat([cipher.update(plaintext, 'utf8'), cipher.final()]);
  const version = Buffer.alloc(2);
  version.writeUInt16BE(keyVersion);
  return Buffer.concat([version, iv, ct, cipher.getAuthTag()]);
}

export function decryptField(keysByVersion, blob, aad) {
  if (!Buffer.isBuffer(blob) || blob.length < 2 + 12 + 16) throw new Error('ciphertext too short');
  const version = blob.readUInt16BE(0);
  const key = keysByVersion.get(version);
  if (!key) throw new Error('unknown key_version');
  const iv = blob.subarray(2, 14);
  const tag = blob.subarray(blob.length - 16);
  const decipher = createDecipheriv('aes-256-gcm', key, iv, { authTagLength: 16 });
  decipher.setAAD(Buffer.from(aad));
  decipher.setAuthTag(tag);
  return Buffer.concat([decipher.update(blob.subarray(14, blob.length - 16)), decipher.final()]).toString('utf8');
}
