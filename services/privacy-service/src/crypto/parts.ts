import { CryptoError } from './errors';

export const SUBJECT_TYPES = ['CUSTOMER', 'ACCOUNT'] as const;
export type SubjectType = (typeof SUBJECT_TYPES)[number];

/** The vault columns that hold an identity attribute (PRD 11, identity_vault). */
export const VAULT_COLUMNS = ['customer_id', 'nik', 'nama', 'hp', 'rekening'] as const;
export type VaultColumn = (typeof VAULT_COLUMNS)[number];

const UUID = /^[0-9a-f]{8}-[0-9a-f]{4}-4[0-9a-f]{3}-[89ab][0-9a-f]{3}-[0-9a-f]{12}$/;

/**
 * A lone surrogate becomes U+FFFD when encoded, so two different ids could produce the same bytes (same lookup, same
 * AAD) and a plaintext would not round-trip. Refused instead of being altered silently.
 */
export function assertWellFormed(text: string): void {
  // Round trip instead of String.isWellFormed: the project's TypeScript lib does not include ES2024.
  if (Buffer.from(text, 'utf8').toString('utf8') !== text)
    throw new CryptoError('malformed', 'the text is not well-formed Unicode');
}

/** The value is not empty: an empty id or service would give every such subject one shared lookup or token. */
export function assertPresent(name: string, text: string): void {
  if (text === '') throw new CryptoError('malformed', `${name} is empty`);
}

/**
 * "||" of PRD 6 and 6.2 made unambiguous: every part gets a 4-byte big-endian length in front (ADR-0011, item 2).
 * Bare concatenation lets ("CUST-1", "2") and ("CUST-12", "") collide.
 */
export function encodeParts(...parts: readonly string[]): Buffer {
  return Buffer.concat(
    parts.flatMap((part) => {
      assertWellFormed(part);
      const bytes = Buffer.from(part, 'utf8');
      const length = Buffer.alloc(4);
      length.writeUInt32BE(bytes.length);
      return [length, bytes];
    }),
  );
}

declare const rowBindingBrand: unique symbol;
/**
 * The AAD of a ciphertext. It can only be made by `mappingBinding` and `vaultBinding`, so no caller can pass an
 * empty or hand-made AAD to `FieldCipher` (T-16).
 */
export type RowBinding = Buffer & { readonly [rowBindingBrand]: true };

/** A random (version 4) UUID: the row ids and nonces are generated by the application (ADR-0011). */
export function isUuid(value: string): boolean {
  return UUID.test(value);
}

export function isSubjectType(value: string): value is SubjectType {
  return (SUBJECT_TYPES as readonly string[]).includes(value);
}

// Every binding made here is remembered with a private copy of its bytes, so FieldCipher can refuse one that was cast
// or built by hand, and a caller that changes an issued Buffer (a Buffer cannot be frozen) changes nothing.
const issued = new WeakMap<Buffer, Buffer>();

function bind(...parts: string[]): RowBinding {
  const binding = encodeParts(...parts) as RowBinding;
  issued.set(binding, Buffer.from(binding));
  return binding;
}

/** The AAD bytes of a binding returned by `mappingBinding` or `vaultBinding`; undefined for any other value. */
export function issuedBytes(value: unknown): Buffer | undefined {
  return Buffer.isBuffer(value) ? issued.get(value) : undefined;
}

/** The row id is generated by the application before the INSERT (ADR-0011), so it is known when encrypting. */
function assertRowId(rowId: string): void {
  if (!isUuid(rowId)) throw new CryptoError('malformed', 'the row id is not a UUID v4');
}

/** Mapping: AAD = 'mapping', subject_type, id. It holds no subject_lookup, so rotating K_index breaks nothing. */
export function mappingBinding(subjectType: string, rowId: string): RowBinding {
  if (!isSubjectType(subjectType)) throw new CryptoError('malformed', 'unknown subject type');
  assertRowId(rowId);
  return bind('mapping', subjectType, rowId);
}

/** Vault: AAD = 'vault', column, id. */
export function vaultBinding(column: string, rowId: string): RowBinding {
  if (!(VAULT_COLUMNS as readonly string[]).includes(column)) {
    throw new CryptoError('malformed', 'unknown vault column');
  }
  assertRowId(rowId);
  return bind('vault', column, rowId);
}
